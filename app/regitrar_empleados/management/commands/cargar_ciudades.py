class Command(BaseCommand):
    help = 'Carga las ciudades desde la lista CIUDAD_DATA en la base de datos'

    def handle(self, *args, **kwargs):
        creados = 0
        actualizados = 0
        existentes = 0
        errores = 0

        self.stdout.write(self.style.MIGRATE_HEADING('Cargando ciudades...'))

        for entrada in CIUDAD_DATA:
            try:
                str_repr, nombre_ciudad = entrada

                # Extraer los códigos del string con formato __str__
                partes = [p.strip() for p in str_repr.split(' - ')]
                if len(partes) != 4:
                    self.stdout.write(self.style.ERROR(f'❌ Formato inválido: "{str_repr}"'))
                    errores += 1
                    continue

                codigo_pais, codigo_departamento, codigo_dane, _ = partes

                # Crear o actualizar usando los campos únicos
                obj, creado = Ciudad.objects.update_or_create(
                    codigo_pais=codigo_pais,
                    codigo_departamento=codigo_departamento,
                    codigo_dane=codigo_dane,
                    defaults={'nombre_ciudad': nombre_ciudad}
                )

                if creado:
                    creados += 1
                    self.stdout.write(self.style.SUCCESS(f'✅ Creada: {obj}'))
                else:
                    # Ya existía, verificar si cambió el nombre
                    if obj.nombre_ciudad != nombre_ciudad:
                        obj.nombre_ciudad = nombre_ciudad
                        obj.save()
                        actualizados += 1
                        self.stdout.write(self.style.WARNING(f'↻ Actualizada: {obj}'))
                    else:
                        existentes += 1
                        self.stdout.write(f'ℹ️  Existente: {obj}')

            except Exception as e:
                errores += 1
                self.stdout.write(self.style.ERROR(f'❌ Error en "{str_repr}": {e}'))

        self.stdout.write(self.style.SUCCESS(
            f'\n📊 Ciudades — Creadas: {creados} | Actualizadas: {actualizados} | Existentes: {existentes} | Errores: {errores}'
        ))